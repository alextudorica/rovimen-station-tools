#!/usr/bin/env python3
"""rtsp_relay.py - the loopback RTSP relay's camera map, and pointing RMS and
colour capture at it.

setup_rtsp_relay.sh installs MediaMTX and runs this for everything that reads
config.json or the RMS configs:

  yaml     write mediamtx.yml: one relay path per camera with a camera_rtsp
  rms      point every RMS instance's ``device:`` line at its camera's path
           and restart that RMS service
  capture  set stations.<CAM>.capture_rtsp to the camera's path (config_patch)
           and restart colour capture

RMS takes the camera it controls over DVRIP (the day/night mode switch, camera
reboots) from the first dotted-quad IP in its device URL (RMS
Utils/CameraControl.py, cameraControlV2). A relay URL on 127.0.0.1 would make
RMS control 127.0.0.1, so RMS gets ``rtsp://localhost:8554/<path>?camera=<IP>``:
the host is a name, the camera IP is the first dotted quad, and MediaMTX
ignores the query. Colour capture does no camera control and reads
``rtsp://127.0.0.1:8554/<path>``.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, NamedTuple, Optional, Tuple

import rovimen_rms

SCRIPTS_DIR = Path.home() / 'rovimen_scripts'
DEFAULT_CONFIG = SCRIPTS_DIR / 'config.json'
DEFAULT_PORT = 8554
PUBLISHER_TIMEOUT_US = 10_000_000

_URL_HOST = re.compile(r'^rtsp://(?:[^/@]*@)?([^:/?]+)')
# Units that run RMS capture, across the fleet's install layouts
# (rms-cam1, rms.service, rms-capture-cam2, gmn-capture-RO0003, ...).
_RMS_UNIT_GLOBS = ('rms*.service', 'gmn-capture*.service')


class RelayPath(NamedTuple):
    name: str        # MediaMTX path name (cam1, gh662s, ...)
    station_id: str  # camera code in config.json
    url: str         # the camera's own RTSP URL, as MediaMTX pulls it
    host: str        # the camera's IP


class RmsInstance(NamedTuple):
    unit: str
    user_scope: bool
    config: Path


def camera_host(url: str) -> Optional[str]:
    """Host of an RTSP URL, userinfo stripped."""
    m = _URL_HOST.match((url or '').strip())
    return m.group(1) if m else None


rms_control_ip = rovimen_rms.camera_ip_from_device


def _url_tail(url: str) -> str:
    """The stream part of an RTSP URL (after host:port), for comparing streams."""
    return re.sub(r'^rtsp://(?:[^/@]*@)?[^/]+', '', (url or '').strip())


def relay_paths(cfg: dict) -> Dict[str, RelayPath]:
    """One relay path per camera with a camera_rtsp, keyed by path name.

    The name is ``camN`` from the camera's rms_data_path when it has one (so it
    lines up with RMS_camN), else the lowercased camera code.
    """
    paths: Dict[str, RelayPath] = {}
    for sid, st in (cfg.get('stations') or {}).items():
        if not isinstance(st, dict):
            continue
        url = (st.get('camera_rtsp') or '').strip()
        host = camera_host(url)
        if not url or not host:
            continue
        m = re.search(r'(cam\d+)\b', st.get('rms_data_path') or '')
        name = m.group(1) if m else sid.lower()
        # MediaMTX rejects rtsp://user:@host (a username with an empty
        # password). XMEye cameras carry their credentials in the query
        # (user=...&password=...), so drop the empty userinfo.
        url = re.sub(r'^(rtsp://)[^/@]*:@', r'\1', url)
        paths[name] = RelayPath(name, sid, url, host)
    return paths


def mediamtx_yaml(paths: Dict[str, RelayPath], bind: str, restamp: bool = False) -> str:
    """mediamtx.yml for these paths, listening on ``bind`` (host:port) only."""
    bind_host, port = bind.rsplit(':', 1)
    pub_host = bind_host.replace('0.0.0.0', '127.0.0.1')
    lines = [
        '# Generated by setup_rtsp_relay.sh - do not edit by hand.',
        '# Loopback RTSP relay: one shared upstream pull per camera, fanned out to',
        '# RMS detection + color capture. Regenerate by re-running the setup script.',
        'logLevel: info',
        'logDestinations: [stdout]',
        'readTimeout: 20s',
        'writeTimeout: 20s',
        'api: no',
        'metrics: no',
        'pprof: no',
        'playback: no',
        'rtmp: no',
        'hls: no',
        'webrtc: no',
        'srt: no',
        'moq: no',
        'rtsp: yes',
        f'rtspAddress: {bind}',
        # The RTP/RTCP UDP helper sockets bind to the same (loopback) host, so
        # the relay exposes nothing beyond the RTSP port.
        f'rtpAddress: {bind_host}:8000',
        f'rtcpAddress: {bind_host}:8001',
        'paths:',
    ]
    for name in sorted(paths):
        url = paths[name].url
        if restamp:
            # Opt-in (see setup_rtsp_relay.sh): an ffmpeg publisher re-stamps
            # the camera's RTP pace to the host wall clock, which keeps RMS
            # time on the host clock for cameras that run slightly slow
            # (known failure mode 54). -c copy: no re-encode, still one
            # camera pull.
            #
            # runOnInit, not runOnDemand: MediaMTX stops an on-demand command
            # with one SIGINT, and ffmpeg can hang in its graceful RTSP
            # teardown, so the stopped publisher kept pulling the camera while
            # the next reader started a second one (every camera on gmnro01
            # (Ghirdoveni) had two pulls by 12:30 UTC on 2026-09-28). A
            # publisher that always runs is never stopped; systemd kills the
            # whole group when the relay stops. -timeout (ffmpeg >= 5: socket
            # I/O timeout, microseconds) ends a stalled camera read so
            # runOnInitRestart reconnects.
            shell_url = url.replace("'", "'\\''")
            cmd = (
                'ffmpeg -nostdin -loglevel error -rtsp_transport tcp'
                f' -timeout {PUBLISHER_TIMEOUT_US}'
                ' -use_wallclock_as_timestamps 1'
                f" -i '{shell_url}'"
                ' -c copy -f rtsp -rtsp_transport tcp'
                f' rtsp://{pub_host}:{port}/{name}'
            )
            lines += [
                f'  {name}:',
                '    runOnInit: >',
                f'      {cmd}',
                '    runOnInitRestart: yes',
            ]
        else:
            url_q = url.replace('"', '\\"')
            lines += [
                f'  {name}:',
                f'    source: "{url_q}"',
                '    rtspTransport: tcp',
                '    sourceOnDemand: yes',
                '    sourceOnDemandStartTimeout: 10s',
                '    sourceOnDemandCloseAfter: 60s',
            ]
    return '\n'.join(lines) + '\n'


def rms_device_url(path: RelayPath, port: int, old_device: str = '') -> str:
    """RMS's relay device URL for ``path``.

    Carries the camera IP so RMS's camera control reaches the camera, plus the
    DVRIP credentials when the old device URL had a non-empty password (RMS
    defaults to admin with an empty password, the XMEye factory login).
    """
    url = f'rtsp://localhost:{port}/{path.name}?camera={path.host}'
    user = re.search(r'user=([^&]*)', old_device or '')
    pwd = re.search(r'password=([^&]*)', old_device or '')
    if pwd and pwd.group(1):
        url += f"&user={user.group(1) if user else 'admin'}&password={pwd.group(1)}"
    return url


def _read_device(config: Path) -> Optional[str]:
    for line in config.read_text().splitlines():
        if line.startswith('device:'):
            return line.split(':', 1)[1].strip()
    return None


def relay_path_for_device(device: str, paths: Dict[str, RelayPath],
                          port: int) -> Tuple[Optional[RelayPath], str]:
    """The relay path an RMS device URL reads, and why when there is none.

    Handles a direct camera URL, the older ``rtsp://127.0.0.1:<port>/<path>``
    relay form, and this module's own form (so a re-run is a no-op).
    """
    host = camera_host(device)
    if host in ('127.0.0.1', 'localhost'):
        m = re.match(rf'^rtsp://[^/]+:{port}/([^?/]+)', device)
        if m and m.group(1) in paths:
            return paths[m.group(1)], ''
        return None, f'relay URL with an unknown path: {device}'
    ip = rms_control_ip(device)
    matches = [p for p in paths.values() if p.host == ip]
    if not matches:
        return None, f'no camera_rtsp in config.json for camera {ip}'
    path = matches[0]
    if _url_tail(device) != _url_tail(path.url):
        return None, (f'RMS reads {_url_tail(device)!r} but the relay pulls '
                      f'{_url_tail(path.url)!r} from {ip}; repoint by hand')
    return path, ''


def repoint_rms_config(config: Path, paths: Dict[str, RelayPath], port: int,
                       stamp: str, dry_run: bool = False) -> Tuple[bool, str]:
    """Point one RMS config's device line at its camera's relay path.

    Returns (changed, message). A change is backed up to
    ``<config>.bak.relay.<stamp>`` first.
    """
    device = _read_device(config)
    if device is None:
        return False, f'{config}: no device line'
    path, why = relay_path_for_device(device, paths, port)
    if path is None:
        return False, f'{config}: skipped, {why}'
    new = rms_device_url(path, port, device)
    if device == new:
        return False, f'{config}: already {new}'
    if not dry_run:
        shutil.copy2(config, f'{config}.bak.relay.{stamp}')
        text = config.read_text()
        config.write_text(re.sub(r'(?m)^device:.*$', lambda _m: f'device: {new}', text, count=1))
    return True, f'{config}: {device} -> {new}'


def _systemctl(user_scope: bool, *args: str) -> subprocess.CompletedProcess:
    cmd = ['systemctl', '--user'] if user_scope else ['sudo', '-n', 'systemctl']
    return subprocess.run(cmd + list(args), capture_output=True, text=True)


def rms_instances() -> List[RmsInstance]:
    """Every loaded RMS capture service (system and user scope) and its config.

    The config is ExecStart's ``-c <path>``, else ``<WorkingDirectory>/.config``.
    """
    found: List[RmsInstance] = []
    for user_scope in (False, True):
        base = ['systemctl', '--user'] if user_scope else ['systemctl']
        listing = subprocess.run(
            base + ['list-units', '--all', '--plain', '--no-legend', '--type=service']
            + list(_RMS_UNIT_GLOBS),
            capture_output=True, text=True).stdout
        for line in listing.splitlines():
            unit = line.split()[0] if line.split() else ''
            if not unit.endswith('.service'):
                continue
            show = subprocess.run(base + ['show', unit, '-p', 'ExecStart', '-p', 'WorkingDirectory'],
                                  capture_output=True, text=True).stdout
            if 'StartCapture' not in show:
                print(f'NOTE {unit}: ExecStart does not run RMS.StartCapture, skipped')
                continue
            m = re.search(r'-c\s+(\S+?)\s*;', show) or re.search(r'-c\s+(\S+)', show)
            wd = re.search(r'^WorkingDirectory=(\S+)', show, re.M)
            config = Path(m.group(1)) if m else (Path(wd.group(1)) / '.config' if wd else None)
            if config is not None and config.is_file():
                found.append(RmsInstance(unit, user_scope, config))
            else:
                print(f'WARN {unit}: RMS config not found (ExecStart/WorkingDirectory)')
    return found


def capture_patch(cfg: dict, paths: Dict[str, RelayPath], port: int) -> dict:
    """The config_patch object pointing every relayed camera's colour capture
    at its relay path."""
    return {'stations': {p.station_id: {'capture_rtsp': f'rtsp://127.0.0.1:{port}/{p.name}'}
                         for p in paths.values()}}


def _restart_colour_capture() -> str:
    for user_scope in (False, True):
        base = ['systemctl', '--user'] if user_scope else ['systemctl']
        active = subprocess.run(base + ['is-active', 'color-capture.service'],
                                capture_output=True, text=True).stdout.strip()
        if active == 'active':
            r = _systemctl(user_scope, 'restart', 'color-capture.service')
            scope = 'user' if user_scope else 'system'
            return f'restarted {scope} color-capture.service' if r.returncode == 0 \
                else f'FAILED to restart {scope} color-capture.service: {r.stderr.strip()}'
    return 'no active color-capture.service to restart'


def _load(config: Path) -> dict:
    with open(config) as f:
        return json.load(f)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('command', choices=('yaml', 'rms', 'capture'))
    ap.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    ap.add_argument('--bind', default=f'127.0.0.1:{DEFAULT_PORT}')
    ap.add_argument('--out', type=Path, help='yaml: where to write mediamtx.yml')
    ap.add_argument('--restamp', action='store_true',
                    help='publish through the ffmpeg re-stamping shim (see setup_rtsp_relay.sh)')
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args(argv)

    cfg = _load(args.config)
    paths = relay_paths(cfg)
    if not paths:
        print('No cameras with a camera_rtsp in config.json', file=sys.stderr)
        return 1
    port = int(args.bind.rsplit(':', 1)[1])

    if args.command == 'yaml':
        text = mediamtx_yaml(paths, args.bind, restamp=args.restamp)
        if args.out and not args.dry_run:
            args.out.write_text(text)
        for name in sorted(paths):
            print(f'{name}\t{paths[name].station_id}\t{paths[name].host}')
        return 0

    if args.command == 'rms':
        stamp = datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')
        rc = 0
        for inst in rms_instances():
            changed, msg = repoint_rms_config(inst.config, paths, port, stamp, args.dry_run)
            print(f'{inst.unit}: {msg}')
            if changed and not args.dry_run:
                r = _systemctl(inst.user_scope, 'restart', inst.unit)
                print(f'{inst.unit}: ' + ('restarted' if r.returncode == 0
                                          else f'RESTART FAILED {r.stderr.strip()}'))
                rc = rc or r.returncode
        return rc

    # capture
    if cfg.get('color_tee'):
        print('color_tee is on: colour capture reads RMS recordings, capture_rtsp unused')
        return 0
    patch = capture_patch(cfg, paths, port)
    if args.dry_run:
        print(json.dumps(patch, indent=2))
        return 0
    import config_patch
    config_patch.patch_config(patch, args.config)
    for p in sorted(paths.values()):
        print(f'{p.station_id}: capture_rtsp rtsp://127.0.0.1:{port}/{p.name}')
    print(_restart_colour_capture())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
