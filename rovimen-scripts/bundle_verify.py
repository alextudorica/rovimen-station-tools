#!/usr/bin/env python3
"""bundle_verify.py — station-side verification of CI-signed update bundles.

``updater.sh`` downloads the station bundle from the VPS into a staging
directory and runs this verifier **before** any file touches the live install.
The trust anchor is an ed25519 public key pinned at
``/etc/rovimen/bundle_signing_pub.pem`` — root-owned, delivered over SSH only,
NEVER fetched from the VPS or taken from the bundle itself. CI signs the
bundle with the matching private key (GitHub secret ``BUNDLE_SIGNING_KEY``);
a compromised VPS can rearrange bytes in the bundle directory all it wants,
but cannot produce a signature the pin accepts.

Checks (all fail-closed in ``enforce`` mode):

1. **Signature** — ``MANIFEST.sig`` is a valid ed25519 signature over the exact
   ``MANIFEST`` file bytes, against any pinned key (multiple concatenated PEM
   blocks in the pin file are accepted, enabling dual-pin key rotation).
2. **Channel binding** — the manifest's ``channel`` must equal the station's
   ``update_channel`` (a dev bundle can never be replayed onto a main station).
3. **Anti-rollback** — on the same channel the manifest ``build`` (CI run
   number, monotonic per channel) must not be lower than the build that is
   INSTALLED, read from the live ``.version`` (which ``updater.sh`` writes only
   after an update has fully gone in). Re-applying the installed build is
   allowed, so a run that verified build N and then died before installing it
   retries N instead of refusing it forever (gmnro05 (Bistrița), 2026-11-06 and
   11-17). With no readable ``.version`` the last verified build in the state
   file is the floor, again with equality allowed. A channel *change* resets
   the counter (switching channels already requires SSH access to edit
   config.json).
4. **Exact set** — every file in staging is listed in the manifest with a
   matching sha256, and every manifest entry exists in staging. Extra files
   fail (only ``MANIFEST``/``MANIFEST.sig`` are exempt).

Mode comes from ``/etc/rovimen/update_verify_mode`` (root-owned): ``warn``
logs failures but lets the update proceed (exit 0); ``enforce`` rejects it
(exit 1). A missing mode file means ``warn`` so the fleet rollout is safe on
stations that have not had their SSH pin round yet.

State is persisted to ``~/rovimen_scripts/.bundle_state.json`` — read by
``station_api.py`` for heartbeat telemetry. ``build``/``version`` there are the
last VERIFIED bundle; the installed one is ``.version``. ``update`` records how
the latest update attempt ended (``--record-update``, written by updater.sh):
``started`` (verified, not yet complete), ``applied`` (``.version`` written),
``ok`` / ``unhealthy`` (post-restart health check) or ``failed``.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import logging
import os
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger("rovimen_updater.bundle_verify")

MANIFEST_NAME = "MANIFEST"
SIGNATURE_NAME = "MANIFEST.sig"
# Files allowed in staging without a manifest entry.
EXEMPT_FILES = frozenset({MANIFEST_NAME, SIGNATURE_NAME})

# Interpreter-generated bytecode. Never shipped, never manifested, and created
# by the mere act of importing a bundle module -- which is exactly how two stray
# ``__pycache__/*.pyc`` files under the VPS bundle dir (root-owned, written
# 2026-08-17) made every station reject build 220 four times a day for three
# days with "extra file not in manifest", freezing the whole fleet on 218.
#
# These are PRUNED from staging rather than exempted: an exemption would be a
# permanent hole where an unverified file may sit next to verified sources, and
# ``__pycache__`` is the one directory an attacker can predict. Deleting keeps
# the exact-set check total -- every file that survives to the install step is
# still manifest-matched.
BYTECODE_DIR = "__pycache__"

VALID_MODES = ("warn", "enforce")

# Outcomes updater.sh records for an update attempt (``--record-update``).
UPDATE_STATUSES = ("started", "applied", "ok", "unhealthy", "failed")

# Stable token stamped on every "the station refused a bundle" log line, here
# and in updater.sh. Prose around it may change; this token may not. It is what
# a fleet-wide sweep greps for:
#
#     for s in $stations; do ssh $s "grep -c ROVIMEN_BUNDLE_REJECTED ~/logs/updater.log"; done
#
# A rejection emits it twice (verifier, then updater) — grep for presence, not
# for a count of update cycles.
REJECT_MARKER = "ROVIMEN_BUNDLE_REJECTED"

# All paths env-overridable for tests. The pin and mode files live under
# /etc/rovimen (root-owned) so a compromise of the station user cannot
# silently disable verification.
DEFAULT_PUBKEY_PATH = Path(
    os.environ.get("ROVIMEN_BUNDLE_PUBKEY", "/etc/rovimen/bundle_signing_pub.pem")
)
DEFAULT_MODE_PATH = Path(
    os.environ.get("ROVIMEN_UPDATE_VERIFY_MODE_FILE", "/etc/rovimen/update_verify_mode")
)
DEFAULT_STATE_PATH = Path(
    os.environ.get(
        "ROVIMEN_BUNDLE_STATE",
        str(Path.home() / "rovimen_scripts" / ".bundle_state.json"),
    )
)


@dataclass
class VerifyResult:
    """Outcome of a bundle verification. ``ok`` is the pure verdict; the
    warn/enforce decision is layered on top by the CLI."""

    ok: bool
    failures: list[str] = field(default_factory=list)
    manifest: dict | None = None


# ── ed25519 verification (vendored, verify-only, no secret material) ────────
# Same implementation previously vendored in command_verify.py: prefer the
# `cryptography` library when present, fall back to a pure-Python RFC 8032
# verifier so a station with a minimal Python still verifies rather than
# failing open.


def _spki_pem_to_raw(pem_text: str) -> bytes | None:
    """Extract the 32-byte raw ed25519 public key from a PEM SPKI block.

    ed25519 SPKI DER is a fixed 44-byte structure whose last 32 bytes are the
    raw key: ``30 2a 30 05 06 03 2b 65 70 03 21 00 <32 bytes>``."""
    try:
        b64 = "".join(
            line.strip()
            for line in pem_text.splitlines()
            if line.strip() and not line.startswith("-----")
        )
        der = base64.b64decode(b64)
    except Exception:
        return None
    if len(der) == 44 and der[:12] == bytes.fromhex("302a300506032b6570032100"):
        return der[12:]
    # Fallback: raw 32-byte key on disk.
    if len(der) == 32:
        return der
    return None


def load_pinned_keys(path: Path = DEFAULT_PUBKEY_PATH) -> list[bytes]:
    """Return all pinned 32-byte ed25519 public keys from ``path``.

    The pin file may hold multiple concatenated PEM blocks (dual-pin window
    during key rotation). Missing or unparseable file -> empty list; the
    caller decides fail-open (warn) vs fail-closed (enforce)."""
    try:
        text = path.read_text()
    except FileNotFoundError:
        logger.warning("no bundle signing pin at %s", path)
        return []
    except Exception as exc:  # pragma: no cover - defensive
        logger.warning("could not read bundle signing pin %s: %s", path, exc)
        return []
    keys: list[bytes] = []
    block: list[str] = []
    in_block = False
    for line in text.splitlines():
        if line.startswith("-----BEGIN"):
            in_block = True
            block = [line]
        elif line.startswith("-----END"):
            block.append(line)
            raw = _spki_pem_to_raw("\n".join(block))
            if raw is not None and len(raw) == 32:
                keys.append(raw)
            in_block = False
        elif in_block:
            block.append(line)
    if not keys:
        # Whole-file fallback (raw key or single unterminated block).
        raw = _spki_pem_to_raw(text)
        if raw is not None and len(raw) == 32:
            keys.append(raw)
    if not keys:
        logger.error("pin file %s holds no valid ed25519 key", path)
    return keys


def verify_signature(message: bytes, sig_b64: str, pubkey_raw: bytes) -> bool:
    """True iff ``sig_b64`` is a valid ed25519 signature of ``message``.

    Prefers ``cryptography`` (constant-time, audited); falls back to the
    vendored verify-only implementation. Any error -> False (fail closed)."""
    if pubkey_raw is None or len(pubkey_raw) != 32:
        return False
    try:
        sig = base64.b64decode(sig_b64)
    except Exception:
        return False
    if len(sig) != 64:
        return False
    try:
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
        from cryptography.exceptions import InvalidSignature

        pk = Ed25519PublicKey.from_public_bytes(pubkey_raw)
        try:
            pk.verify(sig, message)
            return True
        except InvalidSignature:
            return False
    except Exception:
        # cryptography unavailable — use the vendored verifier.
        try:
            return _ed25519_verify(pubkey_raw, message, sig)
        except Exception:
            return False


# ── Manifest / state handling ────────────────────────────────────────────────


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def prune_bytecode(staging: Path) -> list[str]:
    """Delete every ``__pycache__`` tree under *staging*; return the paths removed.

    Bytecode is generated, not shipped, so it can never have a manifest entry.
    Removing it before the exact-set check keeps that check total while stopping
    a stray ``.pyc`` -- which appears the moment anything imports a bundle module
    in place -- from rejecting an otherwise valid bundle.

    A file that cannot be deleted is returned in the list anyway, so it still
    surfaces as "extra file not in manifest" and fails the bundle rather than
    being silently installed.
    """
    removed: list[str] = []
    for d in sorted(staging.rglob(BYTECODE_DIR)):
        if not d.is_dir():
            continue
        for f in sorted(d.rglob("*")):
            if f.is_file():
                rel = f.relative_to(staging).as_posix()
                try:
                    f.unlink()
                except OSError:
                    continue
                removed.append(rel)
        try:
            d.rmdir()
        except OSError:
            pass
    return removed


def load_state(path: Path = DEFAULT_STATE_PATH) -> dict:
    """Last verified bundle state, or {} if absent/corrupt."""
    try:
        data = json.loads(path.read_text())
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def parse_version(text: str) -> tuple[str, int] | None:
    """(channel, build) from a bundle ``.version`` string, or None.

    CI writes ``<run>.<date>`` for main and ``dev.<run>.<date>`` for the
    retired dev channel; the run number is the manifest ``build``."""
    parts = text.strip().split(".")
    try:
        if parts[0] == "dev":
            return "dev", int(parts[1])
        return "main", int(parts[0])
    except (IndexError, ValueError):
        return None


def read_installed(path: Path) -> tuple[str, int] | None:
    """(channel, build) of the installed bundle from its ``.version``, or None."""
    try:
        return parse_version(path.read_text())
    except OSError:
        return None


def write_state(state: dict, path: Path = DEFAULT_STATE_PATH) -> None:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n")
        tmp.replace(path)
    except Exception as exc:  # pragma: no cover - defensive
        logger.warning("could not write bundle state %s: %s", path, exc)


def read_mode(path: Path = DEFAULT_MODE_PATH) -> str:
    """Verification mode: ``warn`` (default when the file is missing or
    unreadable) or ``enforce``. Unknown contents also mean ``warn`` so a
    corrupted mode file can never brick updates."""
    try:
        mode = path.read_text().strip().lower()
    except Exception:
        return "warn"
    return mode if mode in VALID_MODES else "warn"


def verify_bundle(
    staging: Path,
    channel: str,
    pins: list[bytes],
    state: dict | None = None,
    installed: tuple[str, int] | None = None,
) -> VerifyResult:
    """Pure verification of a staged bundle. No file writes, no exits.

    ``installed`` is the (channel, build) of the live install (its
    ``.version``) and is the anti-rollback floor. Without it the
    previously persisted ``state`` build is the floor; pass neither to skip
    the rollback comparison (first verified install)."""
    failures: list[str] = []
    manifest_path = staging / MANIFEST_NAME
    sig_path = staging / SIGNATURE_NAME

    # 1. Manifest + signature files present and parseable.
    try:
        manifest_bytes = manifest_path.read_bytes()
    except FileNotFoundError:
        return VerifyResult(False, [f"missing {MANIFEST_NAME} in staging"])
    try:
        sig_b64 = sig_path.read_text().strip()
    except FileNotFoundError:
        return VerifyResult(False, [f"missing {SIGNATURE_NAME} in staging"])
    try:
        manifest = json.loads(manifest_bytes)
        if not isinstance(manifest, dict):
            raise ValueError("manifest is not an object")
    except Exception as exc:
        return VerifyResult(False, [f"unparseable {MANIFEST_NAME}: {exc}"])
    if manifest.get("schema") != 1:
        return VerifyResult(False, [f"unsupported manifest schema {manifest.get('schema')!r}"], manifest)

    # 2. Signature over the exact MANIFEST file bytes, against any pin.
    if not pins:
        failures.append("no pinned signing key")
    elif not any(verify_signature(manifest_bytes, sig_b64, pin) for pin in pins):
        failures.append("MANIFEST.sig does not verify against any pinned key")

    # 3. Channel binding.
    m_channel = manifest.get("channel")
    if m_channel != channel:
        failures.append(f"channel mismatch: bundle is {m_channel!r}, station expects {channel!r}")

    # 4. Anti-rollback (same channel only; channel change resets the counter).
    # The floor is the INSTALLED build, not the last verified one: a verify
    # that is not followed by a complete install must not lock that build out.
    # Equality passes, because re-applying the running build is no rollback.
    m_build = manifest.get("build")
    if not isinstance(m_build, int):
        failures.append(f"manifest build is not an integer: {m_build!r}")
    elif installed is not None and installed[0] == m_channel:
        if m_build < installed[1]:
            failures.append(
                f"rollback rejected: bundle build {m_build} < installed build {installed[1]}"
            )
    elif installed is None and state and state.get("channel") == m_channel:
        prev_build = state.get("build")
        if isinstance(prev_build, int) and m_build < prev_build:
            failures.append(
                f"rollback rejected: bundle build {m_build} < last verified build {prev_build}"
                " (no installed .version)"
            )

    # 5. Exact-set file check.
    files = manifest.get("files")
    if not isinstance(files, dict):
        failures.append("manifest has no files map")
    else:
        pruned = prune_bytecode(staging)
        if pruned:
            logger.warning(
                "pruned %d interpreter-generated bytecode file(s) from staging: %s",
                len(pruned), ", ".join(pruned[:4]) + (" ..." if len(pruned) > 4 else ""),
            )
        seen: set[str] = set()
        for p in sorted(staging.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(staging).as_posix()
            if rel in EXEMPT_FILES:
                continue
            seen.add(rel)
            expected = files.get(rel)
            if expected is None:
                failures.append(f"extra file not in manifest: {rel}")
            elif sha256_file(p) != expected:
                failures.append(f"sha256 mismatch: {rel}")
        for rel in sorted(set(files) - seen):
            failures.append(f"manifest entry missing from staging: {rel}")

    return VerifyResult(not failures, failures, manifest)


# ── CLI (called by updater.sh) ───────────────────────────────────────────────


def record_update(
    status: str,
    path: Path = DEFAULT_STATE_PATH,
    version: str | None = None,
    failed_services: list[str] | None = None,
    detail: str | None = None,
) -> dict:
    """Record how the current update attempt ended in the state file.

    Merged into the existing state under ``update`` so the verify fields stay
    as they are; the pusher forwards it with the rest of the bundle telemetry.
    """
    state = load_state(path)
    prev = state.get("update") if isinstance(state.get("update"), dict) else {}
    entry: dict = {
        "status": status,
        "version": version or prev.get("version"),
        "at": datetime.now(timezone.utc).isoformat(),
    }
    if failed_services:
        entry["failed_services"] = failed_services
    if detail:
        entry["detail"] = detail
    state["update"] = entry
    write_state(state, path)
    return entry


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Verify a staged station update bundle.")
    ap.add_argument("--staging", type=Path, help="staged bundle directory")
    ap.add_argument("--channel", help="station update_channel (main|dev)")
    ap.add_argument("--pubkey", type=Path, default=DEFAULT_PUBKEY_PATH,
                    help=f"pinned public key path (default {DEFAULT_PUBKEY_PATH})")
    ap.add_argument("--state", type=Path, default=DEFAULT_STATE_PATH,
                    help=f"bundle state json path (default {DEFAULT_STATE_PATH})")
    ap.add_argument("--installed-version", type=Path, default=None,
                    help="the live install's .version, the anti-rollback floor "
                         "(default: .version next to --state)")
    ap.add_argument("--mode-file", type=Path, default=DEFAULT_MODE_PATH,
                    help=f"verify mode file path (default {DEFAULT_MODE_PATH})")
    ap.add_argument("--no-state", action="store_true",
                    help="verify without recording the result; use for any run "
                         "that will NOT be followed by an install")
    ap.add_argument("--record-update", choices=UPDATE_STATUSES,
                    help="record the outcome of an update attempt and exit "
                         "(no verification)")
    ap.add_argument("--update-version", help="bundle version for --record-update")
    ap.add_argument("--failed-services", default="",
                    help="space-separated services for --record-update unhealthy")
    ap.add_argument("--detail", default="", help="free text for --record-update")
    args = ap.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="[bundle_verify] %(levelname)s %(message)s")

    if args.record_update:
        entry = record_update(args.record_update, args.state, args.update_version,
                              args.failed_services.split(), args.detail or None)
        logger.info("update %s recorded for %s", entry["status"], entry.get("version"))
        return 0
    if args.staging is None or args.channel is None:
        ap.error("--staging and --channel are required to verify")

    def save(state_to_write: dict) -> None:
        """Persist unless the caller asked for a stateless check.

        A verify no longer moves the anti-rollback floor (that is the installed
        .version), but a preflight must still leave no record of a bundle that
        was never installed. Under the old verified-build floor such a record
        on gmnro02 on 2026-08-20 made the station reject the real update with
        "rollback rejected: bundle build 220 <= last verified build 220".
        Pass --no-state for any check that will not be followed by an install.
        """
        if args.no_state:
            logger.info("--no-state: not recording this verification")
            return
        write_state(state_to_write, args.state)

    mode = read_mode(args.mode_file)
    pins = load_pinned_keys(args.pubkey)
    state = load_state(args.state)
    installed = read_installed(args.installed_version or args.state.parent / ".version")
    result = verify_bundle(args.staging, args.channel, pins, state, installed)

    now = datetime.now(timezone.utc).isoformat()
    manifest = result.manifest or {}
    new_state = dict(state)
    new_state.update({
        "channel": manifest.get("channel", state.get("channel")),
        "build": manifest.get("build", state.get("build")),
        "version": manifest.get("version", state.get("version")),
        "last_verify": "ok" if result.ok else "fail",
        "verified_at": now,
        "mode": mode,
        "failures": result.failures,
        # updater.sh reports the install's progress over this entry.
        "update": {"status": "started", "version": manifest.get("version"), "at": now},
    })

    if result.ok:
        save(new_state)
        logger.info("verify OK (%s): channel=%s build=%s version=%s",
                    mode, manifest.get("channel"), manifest.get("build"), manifest.get("version"))
        return 0

    for f in result.failures:
        logger.error("verify FAIL: %s", f)

    if mode == "enforce":
        # Rejected: keep the previous state's channel/build, so the telemetry
        # still names the last bundle that verified.
        rejected = dict(state)
        rejected.update({"last_verify": "fail", "verified_at": now,
                         "mode": mode, "failures": result.failures})
        save(rejected)
        logger.error(
            "%s bundle REJECTED (enforce mode) — live install untouched", REJECT_MARKER
        )
        return 1

    # warn: record the failure but let the update proceed (detection-only
    # transitional mode — strictly better than the old zero-verification pull).
    save(new_state)
    logger.warning("verify failed but mode=warn — proceeding with update")
    return 0


# ── Vendored RFC 8032 ed25519 verify (verify-only, no secret material) ──────
# Pure-Python fallback so a station without `cryptography` still verifies
# rather than failing open. Adapted from the reference implementation in
# RFC 8032.

_p = 2 ** 255 - 19
_d = (-121665 * pow(121666, _p - 2, _p)) % _p
_I = pow(2, (_p - 1) // 4, _p)
_L = 2 ** 252 + 27742317777372353535851937790883648493


def _inv(x: int) -> int:
    return pow(x, _p - 2, _p)


def _x_recover(y: int) -> int:
    xx = (y * y - 1) * _inv(_d * y * y + 1)
    x = pow(xx, (_p + 3) // 8, _p)
    if (x * x - xx) % _p != 0:
        x = (x * _I) % _p
    if x % 2 != 0:
        x = _p - x
    return x


_By = (4 * _inv(5)) % _p
_Bx = _x_recover(_By)
_B = (_Bx % _p, _By % _p, 1, (_Bx * _By) % _p)


def _edwards_add(P, Q):  # type: ignore[no-untyped-def]
    x1, y1, z1, t1 = P
    x2, y2, z2, t2 = Q
    a = ((y1 - x1) * (y2 - x2)) % _p
    b = ((y1 + x1) * (y2 + x2)) % _p
    c = (t1 * 2 * _d * t2) % _p
    dd = (z1 * 2 * z2) % _p
    e = b - a
    f = dd - c
    g = dd + c
    h = b + a
    return ((e * f) % _p, (g * h) % _p, (f * g) % _p, (e * h) % _p)


def _scalarmult(P, e):  # type: ignore[no-untyped-def]
    if e == 0:
        return (0, 1, 1, 0)
    Q = _scalarmult(P, e // 2)
    Q = _edwards_add(Q, Q)
    if e & 1:
        Q = _edwards_add(Q, P)
    return Q


def _to_affine(P):  # type: ignore[no-untyped-def]
    x, y, z, _t = P
    zi = _inv(z)
    return ((x * zi) % _p, (y * zi) % _p)


def _decode_int(s: bytes) -> int:
    return int.from_bytes(s, "little")


def _decode_point(s: bytes):  # type: ignore[no-untyped-def]
    y = _decode_int(s) & ((1 << 255) - 1)
    if y >= _p:
        raise ValueError("bad point")
    x = _x_recover(y)
    if x & 1 != (s[31] >> 7) & 1:
        x = _p - x
    return (x % _p, y % _p, 1, (x * y) % _p)


def _ed25519_verify(pubkey: bytes, message: bytes, signature: bytes) -> bool:
    import hashlib as _hashlib

    if len(signature) != 64 or len(pubkey) != 32:
        return False
    R = _decode_point(signature[:32])
    A = _decode_point(pubkey)
    s = _decode_int(signature[32:])
    if s >= _L:
        return False
    h = _decode_int(_hashlib.sha512(signature[:32] + pubkey + message).digest()) % _L
    sB = _to_affine(_scalarmult(_B, s))
    RhA = _to_affine(_edwards_add(R, _scalarmult(A, h)))
    return sB == RhA


if __name__ == "__main__":
    raise SystemExit(main())
