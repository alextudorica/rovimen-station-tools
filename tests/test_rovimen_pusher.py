class TestSpool:
    def test_add_and_pending(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("detections", "detections", {"seq": 1})
        pending = sp.pending()
        assert len(pending) == 1
        _, endpoint, body = pending[0]
        assert endpoint == "detections"
        assert body == {"seq": 1}
        sp.close()

    def test_heartbeat_coalesces_to_latest(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("heartbeat", "heartbeat", {"seq": 1})
        sp.add("heartbeat", "heartbeat", {"seq": 2})
        sp.add("heartbeat", "heartbeat", {"seq": 3})
        pending = sp.pending()
        assert len(pending) == 1
        assert pending[0][2] == {"seq": 3}
        sp.close()

    def test_detections_do_not_coalesce(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("detections", "detections", {"seq": 1})
        sp.add("detections", "detections", {"seq": 2})
        assert sp.count() == 2
        sp.close()

    def test_remove(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("vitals", "vitals", {"seq": 1})
        row_id = sp.pending()[0][0]
        sp.remove(row_id)
        assert sp.count() == 0
        sp.close()

    def test_bounded_size(self, tmp_path, monkeypatch):
        monkeypatch.setattr(rp, "SPOOL_MAX_ROWS", 5)
        sp = rp.Spool(path=tmp_path / "spool.db")
        for i in range(20):
            sp.add("detections", "detections", {"seq": i})
        assert sp.count() == 5
        # kept the newest
        seqs = sorted(b["seq"] for _, _, b in sp.pending())
        assert seqs == [15, 16, 17, 18, 19]
        sp.close()


# ── publisher send/retry/spool integration ─────────────────────────────────


class _FakePost:
    """Records POST calls and returns a scripted sequence of PostResults."""

    def __init__(self, results):
        self.results = list(results)
        self.calls = []

    def __call__(self, url, key, body, timeout=None):
        self.calls.append((url, key, body))
        if self.results:
            return self.results.pop(0)
        return rp.PostResult(ok=True, status=200)


def _make_publisher(tmp_path):
    # A zero clock keeps seq at 1, 2, 3 so the batching tests can name them.
    seq = rp.SeqCounter(state_path=tmp_path / "state.json", clock=lambda: 0.0)
    spool = rp.Spool(path=tmp_path / "spool.db")
    pub = rp.Publisher("https://vps.example", "gmn0002", "rvmn_key", seq, spool)
    return pub, spool


class TestPublisherSend:
    def test_success_does_not_spool(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        fake = _FakePost([rp.PostResult(ok=True, status=200)])
        monkeypatch.setattr(rp, "post_json", fake)
        ok = pub._send("heartbeat", "heartbeat", {"online": True})
        assert ok is True
        assert spool.count() == 0
        # URL is the ingest path with host_key.
        assert fake.calls[0][0] == \
            "https://vps.example/api/ingest/v1/gmn0002/heartbeat"
        assert fake.calls[0][1] == "rvmn_key"
        spool.close()

    def test_failure_spools_non_detections(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        fake = _FakePost([rp.PostResult(ok=False, status=500)])
        monkeypatch.setattr(rp, "post_json", fake)
        ok = pub._send("vitals", "vitals", {"cpu_pct": 1})
        assert ok is False
        assert spool.count() == 1
        spool.close()

    def test_failure_does_not_spool_detections(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        fake = _FakePost([rp.PostResult(ok=False, status=500)])
        monkeypatch.setattr(rp, "post_json", fake)
        ok = pub._send("detections", "detections", {"detections": []})
        assert ok is False
        assert spool.count() == 0
        spool.close()

    def test_seq_increments_per_send(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        fake = _FakePost([rp.PostResult(ok=True), rp.PostResult(ok=True)])
        monkeypatch.setattr(rp, "post_json", fake)
        pub._send("heartbeat", "heartbeat", {})
        pub._send("vitals", "vitals", {})
        seqs = [c[2]["seq"] for c in fake.calls]
        assert seqs == [1, 2]
        spool.close()

    def test_drain_spool_flushes_then_removes(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        spool.add("vitals", "vitals", rp.build_envelope(1, {"cpu_pct": 1}))
        spool.add("media", "media", rp.build_envelope(2, {}))
        fake = _FakePost([rp.PostResult(ok=True), rp.PostResult(ok=True)])
        monkeypatch.setattr(rp, "post_json", fake)
        pub.drain_spool()
        assert spool.count() == 0
        assert len(fake.calls) == 2
        spool.close()

    def test_drain_spool_stops_on_failure(self, tmp_path, monkeypatch):
        pub, spool = _make_publisher(tmp_path)
        spool.add("vitals", "vitals", rp.build_envelope(1, {}))
        spool.add("media", "media", rp.build_envelope(2, {}))
        # first fails -> stop, both remain buffered
        fake = _FakePost([rp.PostResult(ok=False, status=503)])
        monkeypatch.setattr(rp, "post_json", fake)
        pub.drain_spool()
        assert spool.count() == 2
        assert len(fake.calls) == 1
        spool.close()


def _det_rows(n: int, *, date: str = "20260810") -> list[dict]:
    return [
        {"cam": "RO0003", "date": date,
         "ff_file": f"FF_RO0003_{date}_{i:05d}.fits", "meteor_no": 1}
        for i in range(n)
    ]


class TestChunkDetections:
    """The hot window is 14 rolling days of every camera, so it must go out in
    bounded batches (regression 2026-08-09: one station's window outgrew the
    server cap and every push was rejected whole for two weeks)."""

    def test_batch_size_is_well_under_the_server_cap(self):
        # The VPS cap is 20 000; batches must not ride the ceiling.
        assert rp.DETECTION_BATCH_ROWS <= 2000
        assert rp.DETECTION_BATCH_ROWS >= 500

    def test_splits_into_full_batches_plus_remainder(self):
        batches = rp.chunk_detections(_det_rows(2500), size=1000)
        assert [len(b) for b in batches] == [1000, 1000, 500]

    def test_no_row_is_lost_or_duplicated(self):
        rows = _det_rows(2500)
        batches = rp.chunk_detections(rows, size=1000)
        flat = [r for b in batches for r in b]
        assert len(flat) == len(rows)
        assert {r["ff_file"] for r in flat} == {r["ff_file"] for r in rows}

    def test_short_window_is_a_single_batch(self):
        assert len(rp.chunk_detections(_det_rows(10), size=1000)) == 1

    def test_empty_window_yields_no_batches(self):
        assert rp.chunk_detections([], size=1000) == []

    def test_batches_run_oldest_night_first(self):
        rows = (_det_rows(2, date="20260812") + _det_rows(2, date="20260801")
                + _det_rows(2, date="20260807"))
        batches = rp.chunk_detections(rows, size=2)
        dates = [b[0]["date"] for b in batches]
        assert dates == sorted(dates)
        assert dates[0] == "20260801"

    def test_tolerates_a_missing_or_unparseable_meteor_no(self):
        rows = [
            {"cam": "RO0003", "date": "20260810", "ff_file": "b.fits"},
            {"cam": "RO0003", "date": "20260810", "ff_file": "a.fits",
             "meteor_no": "not-a-number"},
        ]
        batches = rp.chunk_detections(rows, size=10)
        assert [r["ff_file"] for r in batches[0]] == ["a.fits", "b.fits"]

    def test_degenerate_size_does_not_hang(self):
        assert len(rp.chunk_detections(_det_rows(3), size=0)) == 3


